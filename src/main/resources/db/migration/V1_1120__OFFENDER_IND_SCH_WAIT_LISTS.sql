create table OFFENDER_IND_SCH_WAIT_LISTS (
   EVENT_ID NUMBER(10,0) not null,
   REQUEST_DATE DATE not null,
   WAIT_LIST_STATUS VARCHAR2(12) not null,
   STATUS_DATE DATE not null,
   TRANSFER_PRIORITY VARCHAR2(12) not null,
   APPROVED_FLAG VARCHAR2(1) default 'N' not null,
   APPROVED_STAFF_ID NUMBER(10,0),
   OUTCOME_REASON_CODE VARCHAR2(12),
   COMMENT_TEXT_1 VARCHAR2(240),
   COMMENT_TEXT_2 VARCHAR2(240),
   CREATE_DATETIME TIMESTAMP default systimestamp not null,
   CREATE_USER_ID VARCHAR2(32) default USER not null,
   MODIFY_DATETIME TIMESTAMP,
   MODIFY_USER_ID VARCHAR2(32),
   AUDIT_TIMESTAMP TIMESTAMP,
   AUDIT_USER_ID VARCHAR2(32),
   AUDIT_MODULE_NAME VARCHAR2(65),
   AUDIT_CLIENT_USER_ID VARCHAR2(64),
   AUDIT_CLIENT_IP_ADDRESS VARCHAR2(39),
   AUDIT_CLIENT_WORKSTATION_NAME VARCHAR2(64),
   AUDIT_ADDITIONAL_INFO VARCHAR2(256),
   constraint OFFENDER_IND_SCH_WAIT_LISTS_PK primary key (EVENT_ID),
   check ( approved_flag IN ( 'Y' , 'N' )  ),
   constraint OFF_ISWL_STAFF_FK foreign key (APPROVED_STAFF_ID) references STAFF_MEMBERS(STAFF_ID)
);
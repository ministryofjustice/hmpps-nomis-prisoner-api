
create table BED_ASSIGNMENT_HISTORIES (
   OFFENDER_BOOK_ID NUMBER(10,0) not null,
   BED_ASSIGN_SEQ NUMBER(6,0) not null,
   LIVING_UNIT_ID NUMBER(10,0) not null,
   ASSIGNMENT_DATE DATE default SYSDATE not null,
   ASSIGNMENT_TIME DATE default SYSDATE not null,
   ASSIGNMENT_REASON VARCHAR2(12),
   ASSIGNMENT_END_DATE DATE,
   ASSIGNMENT_END_TIME DATE,
   CREATE_DATETIME TIMESTAMP default systimestamp not null,
   CREATE_USER_ID VARCHAR2(32) default USER not null,
   MODIFY_DATETIME TIMESTAMP,
   MODIFY_USER_ID VARCHAR2(32),
   AUDIT_TIMESTAMP TIMESTAMP,
   AUDIT_USER_ID VARCHAR2(32),
   AUDIT_MODULE_NAME VARCHAR2(65),
   AUDIT_CLIENT_USER_ID VARCHAR2(64),
   AUDIT_CLIENT_IP_ADDRESS VARCHAR2(39),
   AUDIT_CLIENT_WORKSTATION_NAME VARCHAR2(64),
   AUDIT_ADDITIONAL_INFO VARCHAR2(256),
   constraint BED_ASSIGN_HISTORIES_PK primary key (OFFENDER_BOOK_ID, BED_ASSIGN_SEQ),
   constraint BED_AH_OFF_BKG_F1 foreign key (OFFENDER_BOOK_ID) references OFFENDER_BOOKINGS(OFFENDER_BOOK_ID)
);

create index BED_ASSIGNMENT_HISTORIES_NI1 on BED_ASSIGNMENT_HISTORIES (ASSIGNMENT_DATE);
create index BED_ASSIGNMENT_HISTORIES_NI2 on BED_ASSIGNMENT_HISTORIES (LIVING_UNIT_ID);
